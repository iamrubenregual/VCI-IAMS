-- View: Journal Entries with Details
IF EXISTS (SELECT * FROM sys.views WHERE name = 'vw_JournalEntriesWithDetails')
    DROP VIEW vw_JournalEntriesWithDetails;
GO

CREATE VIEW vw_JournalEntriesWithDetails
AS
SELECT
    je.JournalEntryId,
    je.JournalNumber,
    je.FiscalPeriodId,
    fp.PeriodCode,
    fp.PeriodName,
    fy.FiscalYearCode,
    fp.IsClosed AS PeriodIsClosed,
    je.EntryDate,
    je.PostingDate,
    je.JournalEntryTypeId,
    jet.TypeCode AS EntryTypeCode,
    jet.TypeName AS EntryTypeName,
    je.SourceModule,
    je.SourceReference,
    je.Description,
    je.Status,
    je.TotalDebit,
    je.TotalCredit,
    CASE WHEN je.TotalDebit = je.TotalCredit THEN CAST(1 AS BIT) ELSE CAST(0 AS BIT) END AS IsBalanced,
    je.PostedBy,
    je.PostedDate,
    je.ReversalOfJournalEntryId,
    rev.JournalNumber AS ReversalOfJournalNumber,
    (SELECT COUNT(*) FROM JournalEntryLines jel WHERE jel.JournalEntryId = je.JournalEntryId) AS LineCount,
    je.CreatedBy,
    je.CreatedDate,
    je.ModifiedBy,
    je.ModifiedDate
FROM JournalEntries je
INNER JOIN FiscalPeriods fp ON je.FiscalPeriodId = fp.FiscalPeriodId
INNER JOIN FiscalYears fy ON fp.FiscalYearId = fy.FiscalYearId
INNER JOIN JournalEntryTypes jet ON je.JournalEntryTypeId = jet.JournalEntryTypeId
LEFT JOIN JournalEntries rev ON je.ReversalOfJournalEntryId = rev.JournalEntryId;
GO

PRINT '✓ View vw_JournalEntriesWithDetails created.';
GO

-- View: General Ledger Detail (flattened lines for audits and reporting)
IF EXISTS (SELECT * FROM sys.views WHERE name = 'vw_GeneralLedgerDetail')
    DROP VIEW vw_GeneralLedgerDetail;
GO

CREATE VIEW vw_GeneralLedgerDetail
AS
SELECT
    jel.JournalEntryLineId,
    je.JournalEntryId,
    je.JournalNumber,
    je.EntryDate,
    je.PostingDate,
    je.Status AS JournalStatus,
    je.FiscalPeriodId,
    fp.PeriodCode,
    fp.PeriodName,
    fy.FiscalYearCode,
    jel.LineNumber,
    jel.AccountId,
    coa.AccountCode,
    coa.AccountName,
    at.TypeCode AS AccountTypeCode,
    at.Category AS AccountCategory,
    at.NormalBalance,
    jel.DepartmentId,
    d.DepartmentCode,
    d.DepartmentName,
    jel.DebitAmount,
    jel.CreditAmount,
    CASE
        WHEN at.NormalBalance = 'DEBIT' THEN (jel.DebitAmount - jel.CreditAmount)
        ELSE (jel.CreditAmount - jel.DebitAmount)
    END AS NetAmount,
    jel.Description AS LineDescription,
    jel.ReferenceNumber,
    je.SourceModule,
    je.SourceReference
FROM JournalEntryLines jel
INNER JOIN JournalEntries je ON jel.JournalEntryId = je.JournalEntryId
INNER JOIN FiscalPeriods fp ON je.FiscalPeriodId = fp.FiscalPeriodId
INNER JOIN FiscalYears fy ON fp.FiscalYearId = fy.FiscalYearId
INNER JOIN ChartOfAccounts coa ON jel.AccountId = coa.AccountId
INNER JOIN AccountTypes at ON coa.AccountTypeId = at.AccountTypeId
LEFT JOIN Departments d ON jel.DepartmentId = d.DepartmentId;
GO

PRINT '✓ View vw_GeneralLedgerDetail created.';
GO

