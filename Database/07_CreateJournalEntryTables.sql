-- SP: Generate Next Journal Number (JE-YYYY-XXXXXX)
IF EXISTS (SELECT * FROM sys.objects WHERE type = 'P' AND name = 'sp_GetNextJournalNumber')
    DROP PROCEDURE sp_GetNextJournalNumber;
GO

CREATE PROCEDURE sp_GetNextJournalNumber
    @JournalNumber NVARCHAR(30) OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    DECLARE @NextVal BIGINT;
    SELECT @NextVal = NEXT VALUE FOR seq_JournalEntryNumber;
    SET @JournalNumber = 'JE-' + CAST(YEAR(GETDATE()) AS NVARCHAR(4)) + '-' + RIGHT('000000' + CAST(@NextVal AS NVARCHAR(10)), 6);
END
GO

PRINT '✓ SP sp_GetNextJournalNumber created.';
GO

-- SP: Post Journal Entry (Enforces accounting validation and updates AccountBalances)
IF EXISTS (SELECT * FROM sys.objects WHERE type = 'P' AND name = 'sp_PostJournalEntry')
    DROP PROCEDURE sp_PostJournalEntry;
GO

CREATE PROCEDURE sp_PostJournalEntry
    @JournalEntryId INT,
    @PostedBy NVARCHAR(100)
AS
BEGIN
    SET NOCOUNT ON;
    BEGIN TRY
        BEGIN TRANSACTION;

        -- 1. Check if Journal Entry exists
        DECLARE @Status NVARCHAR(20);
        DECLARE @FiscalPeriodId INT;
        DECLARE @TotalDebit DECIMAL(18,2);
        DECLARE @TotalCredit DECIMAL(18,2);
        DECLARE @EntryDate DATE;

        SELECT
            @Status = Status,
            @FiscalPeriodId = FiscalPeriodId,
            @TotalDebit = TotalDebit,
            @TotalCredit = TotalCredit,
            @EntryDate = EntryDate
        FROM JournalEntries
        WHERE JournalEntryId = @JournalEntryId;

        IF @Status IS NULL
        BEGIN
            RAISERROR('Journal entry does not exist.', 16, 1);
            ROLLBACK TRANSACTION;
            RETURN -1;
        END

        IF @Status = 'POSTED'
        BEGIN
            RAISERROR('Journal entry is already posted.', 16, 1);
            ROLLBACK TRANSACTION;
            RETURN -2;
        END

        IF @Status IN ('VOID', 'REVERSED')
        BEGIN
            RAISERROR('Cannot post a journal entry that is VOID or REVERSED.', 16, 1);
            ROLLBACK TRANSACTION;
            RETURN -3;
        END

        -- 2. Verify lines exist
        IF NOT EXISTS (SELECT 1 FROM JournalEntryLines WHERE JournalEntryId = @JournalEntryId)
        BEGIN
            RAISERROR('Journal entry must have at least one debit and credit line.', 16, 1);
            ROLLBACK TRANSACTION;
            RETURN -4;
        END

        -- 3. Calculate actual sum of debits and credits from lines
        DECLARE @LineDebit DECIMAL(18,2);
        DECLARE @LineCredit DECIMAL(18,2);

        SELECT
            @LineDebit = ISNULL(SUM(DebitAmount), 0),
            @LineCredit = ISNULL(SUM(CreditAmount), 0)
        FROM JournalEntryLines
        WHERE JournalEntryId = @JournalEntryId;

        IF @LineDebit <> @LineCredit OR @LineDebit <= 0
        BEGIN
            RAISERROR('Total debits must equal total credits and must be greater than zero.', 16, 1);
            ROLLBACK TRANSACTION;
            RETURN -5;
        END

        -- 4. Check if fiscal period is open
        IF EXISTS (SELECT 1 FROM FiscalPeriods WHERE FiscalPeriodId = @FiscalPeriodId AND IsClosed = 1)
        BEGIN
            RAISERROR('Cannot post to a closed fiscal period.', 16, 1);
            ROLLBACK TRANSACTION;
            RETURN -6;
        END

        -- 5. Check that no lines reference header accounts or inactive accounts
        IF EXISTS (
            SELECT 1
            FROM JournalEntryLines jel
            INNER JOIN ChartOfAccounts coa ON jel.AccountId = coa.AccountId
            WHERE jel.JournalEntryId = @JournalEntryId
              AND (coa.IsHeader = 1 OR coa.IsActive = 0)
        )
        BEGIN
            RAISERROR('Journal entry lines cannot reference header accounts or inactive accounts.', 16, 1);
            ROLLBACK TRANSACTION;
            RETURN -7;
        END

        -- 6. Update Journal Entry header
        UPDATE JournalEntries
        SET
            Status = 'POSTED',
            PostingDate = CAST(GETDATE() AS DATE),
            PostedBy = @PostedBy,
            PostedDate = GETDATE(),
            TotalDebit = @LineDebit,
            TotalCredit = @LineCredit,
            ModifiedBy = @PostedBy,
            ModifiedDate = GETDATE()
        WHERE JournalEntryId = @JournalEntryId;

        -- 7. Upsert AccountBalances for each distinct account in this entry
        MERGE AccountBalances AS target
        USING (
            SELECT
                jel.AccountId,
                @FiscalPeriodId AS FiscalPeriodId,
                SUM(jel.DebitAmount) AS TotalDebit,
                SUM(jel.CreditAmount) AS TotalCredit
            FROM JournalEntryLines jel
            WHERE jel.JournalEntryId = @JournalEntryId
            GROUP BY jel.AccountId
        ) AS source
        ON (target.AccountId = source.AccountId AND target.FiscalPeriodId = source.FiscalPeriodId)
        WHEN MATCHED THEN
            UPDATE SET
                target.DebitAmount = target.DebitAmount + source.TotalDebit,
                target.CreditAmount = target.CreditAmount + source.TotalCredit,
                target.ClosingBalance = target.OpeningBalance + (target.DebitAmount + source.TotalDebit) - (target.CreditAmount + source.TotalCredit),
                target.LastUpdated = GETDATE()
        WHEN NOT MATCHED THEN
            INSERT (AccountId, FiscalPeriodId, OpeningBalance, DebitAmount, CreditAmount, ClosingBalance, LastUpdated)
            VALUES (
                source.AccountId,
                source.FiscalPeriodId,
                0,
                source.TotalDebit,
                source.TotalCredit,
                source.TotalDebit - source.TotalCredit,
                GETDATE()
            );

        -- 8. Audit Log
        IF EXISTS (SELECT * FROM sys.tables WHERE name = 'AuditLogs')
        BEGIN
            INSERT INTO AuditLogs (Username, Action, TableName, RecordId, NewValues, ActionDate)
            VALUES (
                @PostedBy,
                'POST',
                'JournalEntries',
                CAST(@JournalEntryId AS NVARCHAR(50)),
                '{"Status":"POSTED","TotalDebit":' + CAST(@LineDebit AS NVARCHAR(30)) + ',"TotalCredit":' + CAST(@LineCredit AS NVARCHAR(30)) + '}',
                GETDATE()
            );
        END

        COMMIT TRANSACTION;
        PRINT '✓ Journal Entry posted successfully.';
        RETURN 0;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0
            ROLLBACK TRANSACTION;

        DECLARE @ErrorMessage NVARCHAR(4000) = ERROR_MESSAGE();
        RAISERROR(@ErrorMessage, 16, 1);
        RETURN -99;
    END CATCH
END
GO

PRINT '✓ SP sp_PostJournalEntry created.';
GO

-- SP: Reverse Journal Entry
IF EXISTS (SELECT * FROM sys.objects WHERE type = 'P' AND name = 'sp_ReverseJournalEntry')
    DROP PROCEDURE sp_ReverseJournalEntry;
GO

CREATE PROCEDURE sp_ReverseJournalEntry
    @OriginalJournalEntryId INT,
    @ReversalPeriodId INT,
    @ReversalDate DATE,
    @ReversedBy NVARCHAR(100),
    @NewJournalEntryId INT OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    BEGIN TRY
        BEGIN TRANSACTION;

        -- 1. Check original entry is POSTED
        DECLARE @OrigStatus NVARCHAR(20);
        DECLARE @OrigNumber NVARCHAR(30);
        DECLARE @OrigDescription NVARCHAR(500);
        DECLARE @OrigTypeId INT;

        SELECT
            @OrigStatus = Status,
            @OrigNumber = JournalNumber,
            @OrigDescription = Description,
            @OrigTypeId = JournalEntryTypeId
        FROM JournalEntries
        WHERE JournalEntryId = @OriginalJournalEntryId;

        IF @OrigStatus IS NULL OR @OrigStatus <> 'POSTED'
        BEGIN
            RAISERROR('Only POSTED journal entries can be reversed.', 16, 1);
            ROLLBACK TRANSACTION;
            RETURN -1;
        END

        -- 2. Check if already reversed
        IF EXISTS (SELECT 1 FROM JournalEntries WHERE ReversalOfJournalEntryId = @OriginalJournalEntryId)
        BEGIN
            RAISERROR('This journal entry has already been reversed.', 16, 1);
            ROLLBACK TRANSACTION;
            RETURN -2;
        END

        -- 3. Check target reversal period is open
        IF EXISTS (SELECT 1 FROM FiscalPeriods WHERE FiscalPeriodId = @ReversalPeriodId AND IsClosed = 1)
        BEGIN
            RAISERROR('Reversal fiscal period is closed.', 16, 1);
            ROLLBACK TRANSACTION;
            RETURN -3;
        END

        -- 4. Get Reversing type id
        DECLARE @RevTypeId INT;
        SELECT @RevTypeId = JournalEntryTypeId FROM JournalEntryTypes WHERE TypeCode = 'REVERSING';
        IF @RevTypeId IS NULL
            SET @RevTypeId = @OrigTypeId;

        -- 5. Generate new JournalNumber
        DECLARE @NewJournalNumber NVARCHAR(30);
        EXEC sp_GetNextJournalNumber @JournalNumber = @NewJournalNumber OUTPUT;

        -- 6. Insert new reversing Journal Entry header
        INSERT INTO JournalEntries (
            JournalNumber,
            FiscalPeriodId,
            EntryDate,
            JournalEntryTypeId,
            SourceModule,
            SourceReference,
            Description,
            Status,
            TotalDebit,
            TotalCredit,
            ReversalOfJournalEntryId,
            CreatedBy,
            CreatedDate
        )
        SELECT
            @NewJournalNumber,
            @ReversalPeriodId,
            @ReversalDate,
            @RevTypeId,
            SourceModule,
            'REV:' + @OrigNumber,
            'Reversal of ' + @OrigNumber + ': ' + @OrigDescription,
            'DRAFT',
            TotalCredit, -- Debits and Credits swapped
            TotalDebit,
            @OriginalJournalEntryId,
            @ReversedBy,
            GETDATE()
        FROM JournalEntries
        WHERE JournalEntryId = @OriginalJournalEntryId;

        SET @NewJournalEntryId = SCOPE_IDENTITY();

        -- 7. Insert swapped lines
        INSERT INTO JournalEntryLines (
            JournalEntryId,
            LineNumber,
            AccountId,
            DepartmentId,
            DebitAmount,
            CreditAmount,
            Description,
            ReferenceNumber,
            CreatedBy,
            CreatedDate
        )
        SELECT
            @NewJournalEntryId,
            LineNumber,
            AccountId,
            DepartmentId,
            CreditAmount, -- Swapped
            DebitAmount,  -- Swapped
            'Reversal: ' + ISNULL(Description, ''),
            ReferenceNumber,
            @ReversedBy,
            GETDATE()
        FROM JournalEntryLines
        WHERE JournalEntryId = @OriginalJournalEntryId;

        -- 8. Mark original entry as REVERSED
        UPDATE JournalEntries
        SET
            Status = 'REVERSED',
            ModifiedBy = @ReversedBy,
            ModifiedDate = GETDATE()
        WHERE JournalEntryId = @OriginalJournalEntryId;

        -- 9. Post the reversal entry
        EXEC sp_PostJournalEntry @JournalEntryId = @NewJournalEntryId, @PostedBy = @ReversedBy;

        COMMIT TRANSACTION;
        PRINT '✓ Reversal journal entry created and posted successfully.';
        RETURN 0;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0
            ROLLBACK TRANSACTION;

        DECLARE @ErrorMessage NVARCHAR(4000) = ERROR_MESSAGE();
        RAISERROR(@ErrorMessage, 16, 1);
        RETURN -99;
    END CATCH
END
GO

PRINT '✓ SP sp_ReverseJournalEntry created.';
