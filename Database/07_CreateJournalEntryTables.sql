-- =============================================
-- 3. Journal Entries Header Table
-- =============================================
IF NOT EXISTS (SELECT * FROM sys.tables WHERE name = 'JournalEntries')
BEGIN
    CREATE TABLE JournalEntries (
        JournalEntryId INT IDENTITY(1,1) PRIMARY KEY,
        JournalNumber NVARCHAR(30) NOT NULL UNIQUE,
        FiscalPeriodId INT NOT NULL,
        EntryDate DATE NOT NULL,
        PostingDate DATE NULL,
        JournalEntryTypeId INT NOT NULL,
        SourceModule NVARCHAR(30) NOT NULL DEFAULT 'GL',
        SourceReference NVARCHAR(100) NULL,
        Description NVARCHAR(500) NOT NULL,
        Status NVARCHAR(20) NOT NULL DEFAULT 'DRAFT',
        TotalDebit DECIMAL(18,2) NOT NULL DEFAULT 0,
        TotalCredit DECIMAL(18,2) NOT NULL DEFAULT 0,
        PostedBy NVARCHAR(100) NULL,
        PostedDate DATETIME NULL,
        ReversalOfJournalEntryId INT NULL,
        CreatedBy NVARCHAR(100) NOT NULL,
        CreatedDate DATETIME NOT NULL DEFAULT GETDATE(),
        ModifiedBy NVARCHAR(100) NULL,
        ModifiedDate DATETIME NULL,

        CONSTRAINT FK_JournalEntries_FiscalPeriod FOREIGN KEY (FiscalPeriodId)
            REFERENCES FiscalPeriods(FiscalPeriodId),
        CONSTRAINT FK_JournalEntries_Type FOREIGN KEY (JournalEntryTypeId)
            REFERENCES JournalEntryTypes(JournalEntryTypeId),
        CONSTRAINT FK_JournalEntries_Reversal FOREIGN KEY (ReversalOfJournalEntryId)
            REFERENCES JournalEntries(JournalEntryId),
        CONSTRAINT CK_JournalEntries_Status CHECK (Status IN ('DRAFT', 'SUBMITTED', 'POSTED', 'REVERSED', 'VOID')),
        CONSTRAINT CK_JournalEntries_DebitsPositive CHECK (TotalDebit >= 0),
        CONSTRAINT CK_JournalEntries_CreditsPositive CHECK (TotalCredit >= 0)
    );

    CREATE INDEX IX_JournalEntries_Number ON JournalEntries(JournalNumber);
    CREATE INDEX IX_JournalEntries_Period ON JournalEntries(FiscalPeriodId);
    CREATE INDEX IX_JournalEntries_Date ON JournalEntries(EntryDate);
    CREATE INDEX IX_JournalEntries_Type ON JournalEntries(JournalEntryTypeId);
    CREATE INDEX IX_JournalEntries_Status ON JournalEntries(Status);
    CREATE INDEX IX_JournalEntries_Source ON JournalEntries(SourceModule, SourceReference);

    PRINT '✓ Table JournalEntries created successfully.';
END
ELSE
BEGIN
    PRINT '! Table JournalEntries already exists.';
END
GO

